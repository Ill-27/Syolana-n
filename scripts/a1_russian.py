def gender(s):
    if s.endswith('ость'):return 'f'
    if s in PLURAL or s in {'волосы','ворота','покупки','танцы','лекарства','овощи','науки'}:return 'p'
    h=s.split()[0]
    if s in MALE_A or h in MALE_A or h=='кофе':return 'm'
    if s in FEM_SOFT or h in FEM_SOFT:return 'f'
    if h.endswith(('а','я')):return 'f'
    if h.endswith(('о','е','ё','мя')) or h in {'кафе','такси','меню','радио','видео','хобби','киви','манго','евро','пенни'}:return 'n'
    if h.endswith(('ая','яя')):return 'f'
    if h.endswith(('ое','ее')):return 'n'
    if h.endswith(('ые','ие')):return 'p'
    return 'm'
def adj(s,g='m',case='nom'):
    # Most input meanings start with a masculine nominative adjective.
    base=s.split(';')[0].strip().split(' как ')[0]
    if ';' in s:base=s.split(';')[0].strip()
    if not base.endswith(('ый','ий','ой')):return base
    stem=base[:-2];soft=base.endswith('ий') and stem[-1] not in 'гкхжшчщ'
    endings={'m':'ий' if soft else base[-2:],'f':'яя' if soft else 'ая','n':'ее' if soft else 'ое','p':'ие' if soft or stem[-1] in 'гкхжшчщ' else 'ые'}
    if case=='acc' and g=='f':endings['f']='юю' if soft else 'ую'
    if case=='prep':endings={'m':'ем' if soft else 'ом','f':'ей' if soft else 'ой','n':'ем' if soft else 'ом','p':'их' if soft or stem[-1] in 'гкхжшчщ' else 'ых'}
    if case=='gen':endings={'m':'его' if soft else 'ого','f':'ей' if soft else 'ой','n':'его' if soft else 'ого','p':'их' if soft or stem[-1] in 'гкхжшчщ' else 'ых'}
    if case=='inst':endings={'m':'им' if soft or stem[-1] in 'гкхжшчщ' else 'ым','f':'ей' if soft else 'ой','n':'им' if soft or stem[-1] in 'гкхжшчщ' else 'ым','p':'ими' if soft or stem[-1] in 'гкхжшчщ' else 'ыми'}
    return stem+endings[g]
def case(s,c='nom',animate=False):
    if c=='nom':return s
    if s in FORMS and c in FORMS[s]:return FORMS[s][c]
    if s in INDECL:return s
    if s in {'покупки','танцы','ворота','естественные науки'}:
        return {'покупки':{'prep':'покупках','gen':'покупок','inst':'покупками'},'танцы':{'prep':'танцах','gen':'танцев','inst':'танцами'},'ворота':{'prep':'воротах','gen':'ворот','inst':'воротами'},'естественные науки':{'prep':'естественных науках','gen':'естественных наук','inst':'естественными науками'}}[s].get(c,s)
    if s=='полицейский':return {'acc':'полицейского','prep':'полицейском','gen':'полицейского','inst':'полицейским'}.get(c,s)
    if s.endswith('ёнок'):return s[:-4]+{'acc':'ёнка','gen':'ёнка','prep':'ёнке','inst':'ёнком'}.get(c,'ёнок')
    if ' ' in s:
        parts=s.split();g=gender(s)
        if parts[0].endswith(('ый','ий','ой','ая','яя','ое','ее','ые','ие')):
            # Restore the adjective to its masculine dictionary form before changing case.
            a=parts[0];a=a[:-2]+('ий' if a.endswith(('яя','ее','ие')) else 'ый') if a.endswith(('ая','яя','ое','ее','ые','ие')) else a
            return adj(a,g,c)+' '+case(parts[1],c,animate)+(' '+' '.join(parts[2:]) if len(parts)>2 else '')
        return case(parts[0],c,animate)+' '+' '.join(parts[1:])
    g=gender(s)
    if c=='acc':
        if s.endswith('а'):return s[:-1]+'у'
        if s.endswith('я') and not s.endswith('мя'):return s[:-1]+'ю'
        if animate and g=='m':return case(s,'gen')
        return s
    if c=='gen':
        if s.endswith('а'):return s[:-1]+('и' if s[-2] in 'гкхжшчщ' else 'ы')
        if s.endswith('я'):return s[:-1]+'и'
        if s.endswith('ь'):return s[:-1]+('и' if g=='f' else 'я')
        if s.endswith('й'):return s[:-1]+'я'
        if s.endswith(('о','е')):return s[:-1]+('а' if s.endswith('о') else 'я')
        return s+'а'
    if c=='prep':
        if s.endswith('ость'):return s[:-1]+'и'
        if s.endswith('ия'):return s[:-1]+'и'
        if s.endswith(('ие','ий')):return s[:-1]+'и'
        if s.endswith('ь') and g=='f':return s[:-1]+'и'
        if s.endswith(('а','я','о','е','ь','й')):return s[:-1]+'е'
        return s+'е'
    if c=='inst':
        if s.endswith('а'):return s[:-1]+'ой'
        if s.endswith('я'):return s[:-1]+'ей'
        if s.endswith('ь'):return s[:-1]+('ью' if g=='f' else 'ем')
        if s.endswith(('е','й')):return s[:-1]+'ем'
        if s.endswith('о'):return s[:-1]+'ом'
        return s+'ом'
    return s
