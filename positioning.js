function apply(){
 const route=(location.hash||'#/').replace(/^#\/?/,'').split('/')[0]||'home';
 if(route==='create-site'||route==='site-editor'||route==='studio'||route==='editor'||route==='admin'){location.hash='#/join';return;}
 if(route==='join')renderJoin();
 else if(route==='terms')renderTerms();
 else if(route==='offer')renderOffer();
 else if(route==='privacy')renderPrivacy();
 else if(route==='legal')renderLegal();
 else if(route==='home')patchHomeCopy();
}

let timer=0;
const schedule=()=>{clearTimeout(timer);timer=setTimeout(apply,0);};
window.addEventListener('hashchange',schedule);
new MutationObserver(schedule).observe(document.getElementById('page'),{childList:true,subtree:true});
schedule();
